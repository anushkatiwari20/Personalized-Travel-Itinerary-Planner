import { useState } from 'react'
import { Link, useNavigate } from 'react-router-dom'
import { motion } from 'framer-motion'
import { Mail, Lock, User, Plane } from 'lucide-react'
import { authAPI, errorMessage } from '../services/api'
import { saveSession } from '../utils/auth'

const Side = () => (
  <div className="auth-side">
    <div className="brand" style={{ color: '#fff', padding: 0 }}>
      <div className="brand-mark" style={{ background: '#fff', color: '#2563eb' }}><Plane size={16} /></div>TravelPlanner
    </div>
    <div>
      <h2>Plan smarter.<br />Travel better.</h2>
      <p style={{ opacity: 0.85, maxWidth: 380, lineHeight: 1.6 }}>Day-by-day itineraries, budget-aware recommendations and optimized routes — generated by AI in seconds.</p>
    </div>
    <small style={{ opacity: 0.7 }}>React · FastAPI · Supabase · Groq</small>
  </div>
)

const AuthForm = ({ mode }) => {
  const navigate = useNavigate()
  const isRegister = mode === 'register'
  const [form, setForm] = useState({ name: '', email: '', password: '' })
  const [error, setError] = useState('')
  const [loading, setLoading] = useState(false)
  const set = (k) => (e) => setForm({ ...form, [k]: e.target.value })

  const submit = async (e) => {
    e.preventDefault()
    setError('')
    setLoading(true)
    try {
      const data = isRegister ? await authAPI.register(form) : await authAPI.login({ email: form.email, password: form.password })
      saveSession(data)
      navigate('/dashboard')
    } catch (err) {
      setError(errorMessage(err, 'Authentication failed'))
    } finally {
      setLoading(false)
    }
  }

  return (
    <div className="auth-wrap">
      <Side />
      <div className="auth-form">
        <motion.form onSubmit={submit} initial={{ opacity: 0, y: 12 }} animate={{ opacity: 1, y: 0 }}>
          <div>
            <h2 style={{ fontSize: 28 }}>{isRegister ? 'Create your account' : 'Welcome back'}</h2>
            <p className="muted" style={{ margin: '6px 0 0' }}>{isRegister ? 'Start planning in under a minute.' : 'Sign in to continue planning.'}</p>
          </div>
          {error && <div className="alert alert-error">{error}</div>}
          {isRegister && (
            <div className="field"><label>Full name</label><div className="input-icon"><User size={16} /><input className="input" required minLength={2} value={form.name} onChange={set('name')} placeholder="Anushka Tiwari" /></div></div>
          )}
          <div className="field"><label>Email</label><div className="input-icon"><Mail size={16} /><input className="input" type="email" required value={form.email} onChange={set('email')} placeholder="you@example.com" /></div></div>
          <div className="field"><label>Password</label><div className="input-icon"><Lock size={16} /><input className="input" type="password" required minLength={8} value={form.password} onChange={set('password')} placeholder="Minimum 8 characters" /></div></div>
          <button className="btn btn-primary btn-lg" disabled={loading} style={{ justifyContent: 'center' }}>
            {loading ? <span className="spinner" /> : isRegister ? 'Create account' : 'Sign in'}
          </button>
          <p className="muted" style={{ textAlign: 'center', fontSize: 14 }}>
            {isRegister ? 'Already have an account? ' : "Don't have an account? "}
            <Link to={isRegister ? '/login' : '/register'} style={{ color: 'var(--primary)', fontWeight: 600 }}>{isRegister ? 'Sign in' : 'Create one'}</Link>
          </p>
        </motion.form>
      </div>
    </div>
  )
}

export const Login = () => <AuthForm mode="login" />
export const Register = () => <AuthForm mode="register" />
